HERE = os.path.dirname(os.path.abspath(__file__))
G = 9.81

# ============================== ПЕРЕМЕННЫЕ (не окончательные) ==============================
VARIANTS_D = [0.180, 0.200, 0.220, 0.240]     # диаметры колеса, м
ALPHA = math.radians(45.0)                    # угол оси ролика к оси колеса
N_ROLLERS = {0.180: 9, 0.200: 10, 0.220: 11, 0.240: 12}   # кандидаты N (переменная!)
ROLLER_D = 0.050                              # диаметр бочки ролика в центре, м
ROLLER_L = 0.070                              # длина ролика, м
WALL_STUP = 0.006                             # толщина стенки ступицы, м (переменная)
AXIS_D = 0.010                                # диаметр оси ролика, м (переменная)
HUB_FLANGE_D = 0.120                          # диаметр приводного фланца, м (переменная)
K_PROFILE = 0.85                              # к-т бочечного профиля (переменная!)
SAFETY_FATIGUE = 2.5                          # к-т запаса на усталость осей (переменная)
SAFETY_STATIC = 1.5                           # к-т запаса на статику (переменная)
M_ROBOT = [300.0, 400.0, 450.0]               # сценарии массы робота, кг (не факт)
K_UNEVEN = 1.35                               # неравномерность загрузки (переменная)
K_DYNAMIC = 2.0                               # ударный к-т стыков/неровностей (переменная)
MU_FLOOR = 0.55                               # сцепление с линолеумом (переменная)
BEARING_C = {"малый (по d_оси)": 4500.0, "средний": 9000.0}   # C, Н (справочный ряд — уточнить)
BEARING_P_EXP = 3.0                           # p для шариковых (3), роликовых (10/3)
STEEL = {"плотность": 7850, "sigma_d": 400e6, "tau_d": 240e6}    # конструкционная сталь (справ.)
ALUM = {"плотность": 2700, "sigma_d": 260e6, "tau_d": 160e6}     # дюралюминий (справ.)
PU = {"плотность": 1150, "E": 0.05e9, "sigma_c": 25e6}           # полиуретан ~60-70 Shore A (справ.)

# ============================== ФУНКЦИИ РАСЧЁТА ==============================
def geometry(D, N, d_roll=ROLLER_D, l_roll=ROLLER_L, k_prof=K_PROFILE):
    """Геометрия колеса. Возвращает dict с формулами и результатами."""
    R = D / 2.0
    # эффективный вклад ролика в радиус: бочка под 45°.
    # r_эф = k_prof * (d/2 * cos(alpha) + L/2 * sin(alpha)) — допущение профиля
    r_eff = k_prof * (d_roll / 2 * math.cos(ALPHA) + l_roll / 2 * math.sin(ALPHA))
    R_axis = R - r_eff                       # радиус установки осей роликов
    # ширина колеса: проекция ролика + зазоры
    W = l_roll * math.sin(ALPHA) + d_roll * math.cos(ALPHA) + 0.010
    # ступица: кольцо наружного R_axis + внутреннее (под фланец)
    hub_out = max(HUB_FLANGE_D * 1.6, R_axis * 1.1)
    # шаг угловой между осями роликов
    phi = 360.0 / N
    # оценка пульсации при переходе контакта (формула: чем больше N и меньше
    # r_эф-непостоянство — тем меньше): дельта_h ~ R*(1-cos(phi/2))*sin^2(alpha)*0.5
    # (аппроксимация; точный расчёт профиля — отдельная задача)
    delta_h = R * (1 - math.cos(math.radians(phi / 2))) * math.sin(ALPHA) ** 2
    # частота «перехода роликов» при скорости v: f = v / (2*pi*R) * N
    return {"D_мм": D * 1000, "R_мм": R * 1000, "N_роликов": N,
            "phi_град": phi, "r_эфф_мм": r_eff * 1000,
            "R_осей_мм": R_axis * 1000, "W_мм": W * 1000,
            "hub_наружный_мм": hub_out * 1000,
            "пульсация_мм_аппр": delta_h * 1000,
            "f_перехода_Гц_при_0.5мс": 0.5 / (2 * math.pi * R) * N,
            "формулы": [
                "r_эф = k_проф * (d_р/2*cos45 + L_р/2*sin45)",
                "R_осей = D/2 - r_эф",
                "W = L_р*sin45 + d_р*cos45 + 10мм",
                "дельта_h = R*(1-cos(180/N))*sin^2(45) * 0.5 [аппроксимация]"]}


def loads(M, n_wheels=4):
    """Нагрузки на одно колесо по сценариям массы (кг -> Н)."""
    out = {}
    W_uniform = M * G / n_wheels
    W_uneven = W_uniform * K_UNEVEN              # потеря одной опоры / перекос
    W_dyn = W_uneven * K_DYNAMIC                 # стыки/неровности (удар)
    F_traction = W_uneven * MU_FLOOR             # сцепление (торможение/разгон)
    F_axial = W_uneven * MU_FLOOR                # осевая сила Mecanum ~ mu*N
    out = {"вертикальная_равномерная_Н": round(W_uniform, 1),
           "вертикальная_неравномерная_Н": round(W_uneven, 1),
           "макс_ударная_Н": round(W_dyn, 1),
           "касательная_сцепление_Н": round(F_traction, 1),
           "осевая_Н": round(F_axial, 1)}
    return out


def axis_check(D, N, W_dyn, F_axial, F_trac, axis_d=AXIS_D):
    """Ось ролика: изгиб (два опора) и срез. Сталь (справ. допуски)."""
    R = D / 2
    r_eff = geometry(D, N)["r_эфф_мм"] / 1000
    R_axis = R - r_eff
    # плечо: ось лежит в гнезде обода; нагрузка посередине пролёта l = 40 мм
    l = 0.040                                   # пер. длина оси между опорами (переменная)
    # макс. вертикальная нагрузка на ОДИН ролик (контакт одного ролика)
    F_r = W_dyn                                 # в момент одиночного контакта
    M_max = F_r * l / 4.0                       # балка на двух опорах, сила посередине
    sigma = 32 * M_max / (math.pi * (axis_d / 2) ** 4) * (axis_d / 2)
    # точнее: sigma = M*c/I, I = pi*d^4/64, c = d/2 -> sigma = 32M/(pi d^3)
    sigma = 32 * M_max / (math.pi * axis_d ** 3)
    tau_cut = F_r / (math.pi * (axis_d / 2) ** 2)     # срез по двум сечениям /2
    tau_cut = F_r / 2.0 / (math.pi * (axis_d / 2) ** 2)
    # зависимость: требуемый диаметр оси под заданный запас (формула)
    d_req = (32 * M_max * SAFETY_STATIC / (math.pi * STEEL["sigma_d"])) ** (1 / 3)
    return {"M_изгиба_Нм": round(M_max, 2),
            "sigma_изгиб_МПа": round(sigma / 1e6, 1),
            "запас_к_400МПа": round(STEEL["sigma_d"] / sigma, 1),
            "tau_срез_МПа": round(tau_cut / 1e6, 1),
            "запас_срез_к_240МПа": round(STEEL["tau_d"] / tau_cut, 1),
            "d_ось_треб_мм_при_запасе_1.5": round(d_req * 1000, 1),
            "формула_d_треб": "d = (32*M*K_зап/(pi*sigma_доп))^(1/3)",
            "статус": "OK" if (STEEL["sigma_d"] / sigma >= SAFETY_STATIC
                               and STEEL["tau_d"] / tau_cut >= SAFETY_STATIC)
                      else "НЕ ХВАТАЕТ ЗАПАСА при текущем d_оси — см. d_треб"}


def bearing_check(W_dyn, F_axial, C=BEARING_C["средний"]):
    """Подшипник оси ролика: L10. p — переменная."""
    P = W_dyn + 1.0 * F_axial                    # эквивалентная нагрузка (переменная)
    L10 = (C / P) ** BEARING_P_EXP               # млн. об.
    # при частоте вращения колеса: ролик вращается ~ v/r_эфф -> об/мин
    return {"P_Н": round(P, 1), "C_Н": C,
            "L10_млн_об": round(L10, 1),
            "срок_при_v0.5мс_часов": round(L10 * 1e6 / (0.5 / (2 * math.pi * 0.12) * 60) / 60, 0)
            if False else "см. формулу L10=(C/P)^p",
            "формула": "L10 = (C/P)^p млн.об; p=3 (шарик.), 10/3 (ролик.) — уточнить"}


def contact_check(W_dyn, d_roll=ROLLER_D):
    """Контакт полиуретан-линолеум (упрощённый Херц): полукруглое тело /
    плоскость: sigma = sqrt(F*E*/(pi*R*...)) — даём формулу и зависимость."""
    R_c = d_roll / 2
    E_star = 1.0 / ((1 - 0.49 ** 2) / PU["E"] + (1 - 0.30 ** 2) / 0.4e9)  # линолеум E~0.4 ГПа
    # линейка Херца для цилиндра/плоскости: p0 = sqrt(F*E*/(pi*R*L))
    L_c = ROLLER_L * 0.6                         # ширина пятна (переменная)
    p0 = math.sqrt(W_dyn * E_star / (math.pi * R_c * L_c))
    return {"p0_МПа": round(p0 / 1e6, 1),
            "доп_PU_МПа": PU["sigma_c"] / 1e6,
            "статус": "OK" if p0 <= PU["sigma_c"] else "превышение доп. PU",
            "формула": "p0 = sqrt(F*E*/(pi*r*L)); E* — приведённый модуль PU+линолеум"}


def mass_estimate(D, N, d_roll=ROLLER_D, l_roll=ROLLER_L):
    """Оценочная масса колеса (Al-ступица, PU-ролики с стальным сердечником).
    Зависимости — явно; точность — порядоковая."""
    R = D / 2
    r_eff = geometry(D, N)["r_эфф_мм"] / 1000
    R_axis = R - r_eff
    # ступица: кольцо (R_axis наружное, 0.35*R_axis внутреннее, ширина W)
    W = geometry(D, N)["W_мм"] / 1000
    V_hub = math.pi * ((R_axis) ** 2 - (0.35 * R_axis) ** 2) * W * 0.45   # с отверстиями ~45%
    m_hub_al = ALUM["плотность"] * V_hub
    m_hub_st = STEEL["плотность"] * V_hub
    # ролики: бочка (цилиндр) PU + сердечник сталь (60% диаметра)
    V_roll = math.pi * (d_roll / 2) ** 2 * l_roll * 0.8
    m_roll = PU["плотность"] * V_roll + STEEL["плотность"] * math.pi * (0.3 * d_roll) ** 2 * l_roll * 0.5
    # оси (N шт): сталь
    m_axes = N * STEEL["плотность"] * math.pi * (AXIS_D / 2) ** 2 * 0.050
    # подшипники (справ. ~15 г шариковых 608-класса)
    m_br = N * 0.015
    return {"ступица_Al_кг": round(m_hub_al, 2), "ступица_сталь_кг": round(m_hub_st, 2),
            "ролики_N_кг": round(N * m_roll, 2), "оси_кг": round(m_axes, 3),
            "подшипники_кг": round(m_br, 3),
            "итого_Al_кг": round(m_hub_al + N * m_roll + m_axes + m_br, 2),
            "итого_сталь_кг": round(m_hub_st + N * m_roll + m_axes + m_br, 2)}


