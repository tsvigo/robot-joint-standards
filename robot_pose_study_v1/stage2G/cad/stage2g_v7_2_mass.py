# -*- coding: utf-8 -*-
"""Этап 2Г, корректировка v7.2 — stage2g_v7_2_mass.py (НОВЫЙ файл; v7.1 не изменяется).

Уточнение задачи 3:
- 500 кг = ИЗВЕСТНАЯ минимальная грузоподъёмность больничного грузового лифта,
  в который должен въезжать робот (требование среды — транспорт подъёмника,
  состоящего из робота и/или его нагрузки — уточняется отдельно).
- Грузоподъёмность СОБСТВЕННОГО подъёмника робота пока НЕ утверждена.
- Величины не смешиваются и не суммируются с массой робота.
Бюджет подсистем — без изменений против v7.1 (переработки нет), переносится с
фиксом формулировок.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))

with open(os.path.join(HERE, "stage2g_v7_1_mass.json"), encoding="utf-8") as f:
    V71 = json.load(f)

# ============ A/B/C/D с уточнённым статусом ============
A = {"величина": "A. Грузоподъёмность больничного грузового лифта", "значение": "500 кг",
     "статус": "ОПРЕДЕЛЕНО (уточнение заказчика, v7.2): минимальная грузоподъёмность "
               "больничного грузового лифта, в который должен въезжать робот",
     "в_массу_робота_входит": False,
     "примечание": "требование среды; к массе робота отношения не имеет, в бюджет "
                   "не входит и не суммируется; грузоподъёмность при въезде "
                   "(робот+нагрузка) — отдельное требование к транспортировке, "
                   "формально ещё не привязано к подъёмнику робота"}
B = {"величина": "B. Грузоподъёмность собственного подъёмника робота",
     "значение": "НЕ УТВЕРЖДЕНА",
     "статус": "⬛ в v7 «бюджет подъёма 500 кг» ошибочно привязывался к A; в v7.1 "
               "помечена неопределённость; в v7.2: величина не утверждена",
     "в_массу_робота_входит": False,
     "примечание": "масса механизма подъёмника зависит от B => не определена; "
                   "в расчётах v7.2 не используется"}
C = {"величина": "C. Полная масса робота", "значение": "НЕ ОПРЕДЕЛЕНА",
     "статус": "сумма подсистем; подтверждено 100 кг (4 модуля)",
     "в_массу_робота_входит": True,
     "примечание": "расчётный сценарий для механики — 400 кг (вместе с диапазоном "
                   "300/450) — НЕ подтверждённая масса, а допущение расчётов"}
D = {"величина": "D. Полезная нагрузка манипуляторов", "значение": "НЕ ЗАДАНА",
     "статус": "⬛ состав и сценарии не определены",
     "в_массу_робота_входит": False,
     "примечание": "в C — только в транспортном положении (складываются)"}

old_note = [c for c in V71["confusion_ABCD"] if c["величина"].startswith("A.")][0]
assert "500" in old_note["значение"], "в v7.1 значение A должно содержать 500 кг"

out = {"confusion_ABCD": [A, B, C, D],
       "budget": V71["budget"],
       "retracted_from_v7": V71["retracted_from_v7"],
       "confirmed_kg": V71["confirmed_kg"],
       "scenario_masses_кг": V71["scenario_masses_кг"],
       "fix_v7_2": {
           "было_v7_1": old_note["статус"],
           "стало_v7_2": A["статус"],
           "B_точно": B["статус"],
           "400кг": "расчётный сценарий, НЕ подтверждённая масса робота",
       },
       "notes": [
           "500 кг = больничный грузовой лифт (требование среды) — ОПРЕДЕЛЕНО в v7.2.",
           "Подъёмник робота: грузоподъёмность не утверждена — отдельно от 500 кг.",
           "Кабина 1100×2100 — условный габарит лифта, из бюджета исключена (v7.1).",
           "Итог массы робота не определён; 400 кг — расчётный сценарий.",
       ]}

print("== A/B/C/D после уточнения (v7.2) ==")
for c in out["confusion_ABCD"]:
    print(f"  {c['величина']}: {c['значение']} | входит в массу: "
          f"{'ДА' if c['в_массу_робота_входит'] else 'НЕТ'}")
    print(f"      {c['статус']}")
print(f"\nБюджет подсистем перенесён без изменений: {len(out['budget'])} строк, "
      f"подтверждено {out['confirmed_kg']} кг; сценарные массы {out['scenario_masses_кг']} кг — параметры.")
print("Итог: масса робота НЕ ОПРЕДЕЛЕНА; 400 кг — расчётный сценарий.")

path = os.path.join(HERE, "stage2g_v7_2_mass.json")
with open(path, "w", encoding="utf-8") as f:
    json.dump(out, f, ensure_ascii=False, indent=1)
print("JSON:", path)
