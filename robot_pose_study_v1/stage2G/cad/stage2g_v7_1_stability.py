import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
G = 9.81
R_C = 0.2215            # м
W_MOD = 0.1069          # м
R_GEO = 0.120           # м
PTS_R = [np.array([R_C, 0]), np.array([0, R_C]),
         np.array([-R_C, 0]), np.array([0, -R_C])]

CHECKS = []


def check(cid, ok, detail):
    CHECKS.append({"id": cid, "ok": bool(ok), "detail": detail})
    print(f"  [{'PASS' if ok else 'FAIL'}] {cid}: {detail}")


# ============ 1. Удержание: эталон виртуальной работой ============
print("== 1. Удержание на уклоне: эталон (виртуальная работа) ==")
# Платформа на уклоне: F = M·g·sinα ≈ M·g·grade вдоль склона.
# Виртуальный сдвиг на δx=1 м: работа силы = F·δx; приводы: Στ_i·δω_i.
# Из кинематики (v7.1, SI): при чистом поступательном ω_i = ±v/r (все |ω|=v/r),
# при равных моментах с знаками по ω: Στ·|ω| = 4τ·v/r = F·v  =>  τ = F·r/4.
M_SCEN = (300.0, 400.0, 450.0)
GRADES = (0.01, 0.02, 0.05)
hold_etalon = {}
print(f"  {'масса':>7} {'уклон':>6} {'F_вдоль':>9} {'τ=F·r/4':>9} | гипотезы ×2:")
for M in M_SCEN:
    for g in GRADES:
        F = M * G * g
        tau = F * R_GEO / 4.0
        hyp2 = {"r_как_диаметр_0.24": F * 0.24 / 4.0,
                "sqrt2_удвоение": F * R_GEO / 4.0 * 2.0,
                "2_колеса_вместо_4": F * R_GEO / 2.0}
        if abs(M - 400.0) < 1e-6 and abs(g - 0.05) < 1e-6:
            print(f"  {M:7.0f} {g:6.0%} {F:9.1f} {tau:9.2f} | "
                  + ", ".join(f"{k}={v:.2f}" for k, v in hyp2.items()))
        hold_etalon[f"M={M:.0f},grade={g:.0%}"] = {
            "F_Н": round(F, 1), "tau_еталон_Нм": round(tau, 2),
            "гипотезы_x2_Нм": {k: round(v, 2) for k, v in hyp2.items()}}
check("H1_эталон", abs(400 * G * 0.05 * R_GEO / 4.0 - 5.89) < 0.05,
      "эталон для 400 кг/5%: τ = F·r/4 = 5.89 Н·м — сходится с JSON v7 (5.9)")

# разбор расхождения 5.9 vs 11.8
discrepancy_hold = {
    "в_отчёте_v7": 5.9, "в_JSON_v7": 5.9,
    "заявлено_пользователем_в_коде": 11.8,
    "воспроизведение": ("код v7 (обе строки формулы) и JSON дают 5.9 — воспроизвести "
                        "11.8 из него НЕ УДАЛОСЬ"),
    "формула_дающая_11.8": "τ = F·r/2 = 196.2·0.12/2 = 11.77 Н·м (=F·0.3536·r·√2, "
                           "=F·0.3536·0.24/√2, =2 колёс вместо 4)",
    "вероятные_причины_появления_11.8": [
        "диаметр вместо радиуса (r=0.24)",
        "×√2 вместо ÷√2 в связке f=√2τ/r",
        "учёт 2 из 4 колёс при передаче F",
    ],
    "эталон": "τ = F·r/4 = 5.89 Н·м на колесо (виртуальная работа 4τ·v/r = F·v)",
}
print("\n== Расхождение удержания 5.9 vs 11.8 ==")
for k in ("воспроизведение", "формула_дающая_11.8", "эталон"):
    print(f"  {k}: {discrepancy_hold[k]}")

# ============ 2. Торможение с выключенным питанием ============
print("\n== 2. Торможение/удержание БЕЗ питания ==")
no_power = {
    "тип_редуктора": "НЕ ИЗВЕСТЕН (запрос RoboCT)",
    "сценарии": [
        {"тип": "планетарный без тормоза", "удержание": "нет (обратно-проводим)",
         "допустимый_уклон": "0% (сползание)"},
        {"тип": "планетарный с ЭМ-тормозом", "удержание": "да, если τ_тормоза ≥ τ_треб",
         "допустимый_уклон": "ограничен τ_тормоза — значение из запроса"},
        {"тип": "червячный", "удержание": "самоторможение (если η_back < 1)",
         "допустимый_уклон": "вопрос КПД back-drive — из запроса"},
    ],
    "требуемые_моменты_без_питания": hold_etalon,
    "внешние_силы_манипуляторов": {
        "модель": "сила F_рук в точке => момент M = F·L => эквивалентный сдвиг ЦМ "
                  "e_экв = M/(M·g) и добавка реакции ΔF = M/(2R_C) на краевых колёсах",
        "пример_50Н_на_0.4м": {"M_Нм": 20.0,
                               "e_экв_мм_при_400кг": round(20.0 / (400 * G) * 1000, 1),
                               "dF_Н_при_400кг": round(20.0 / (2 * R_C), 1)},
        "вывод": "в транспортном положении (руки сложены) силы ограничены; в "
                 "движении с выдвинутыми руками — суммарный вынос ЦМ ограничен "
                 "моделью §4 и должен учитываться в запретах на движение",
    },
}
for s in no_power["сценарии"]:
    print(f"  {s['тип']}: удержание — {s['удержание']}; уклон — {s['допустимый_уклон']}")
ex = no_power["внешние_силы_манипуляторов"]["пример_50Н_на_0.4м"]
print(f"  пример 50 Н на 0.4 м: M=20 Н·м, e_экв={ex['e_экв_мм_при_400кг']} мм, "
      f"ΔF={ex['dF_Н_при_400кг']} Н на краевое колесо")

# ============ 3. Реакции опор: модель ============
print("\n== 3. Реакции опор: модель жёсткой платформы на 4 пружинах ==")
K0 = 100000.0     # Н/м базовая жёсткость (параметр — подвеска не подтверждена)


def reactions(M_kg, ex=0.0, ey=0.0, k_rel=(1.0, 1.0, 1.0, 1.0), h=(0.0, 0.0, 0.0, 0.0),
              pts=None):
    """F_i, Н для 4 колёс. k_rel — относительная жёсткость, h — подъём пола, м."""
    P = np.array(pts) if pts is not None else np.array(PTS_R)
    k = np.array(k_rel) * K0
    Gf = M_kg * G
    b = np.array([Gf, Gf * ex, Gf * ey])
    # F = k⊙δ, δ = [1, x_i, y_i]·[z0, tx, ty] − h_i  => A·u = b, A = Σ k_i·q_i q_i^T
    Q = np.array([[1.0, p[0], p[1]] for p in P])            # 4×3
    A = (Q * k[:, None]).T @ Q                                 # 3×3
    u = np.linalg.solve(A, b + (k * np.array(h)) @ Q)          # с учётом неровностей
    delta = Q @ u - np.array(h)
    F = k * delta
    return F


# 3.1 сверка модели с формулой v7 (без неровностей, одинаковые k)
F_lin = reactions(400, ex=0.100)
F_v7 = 400 * G / 4 * (1 + 2 * 0.100 * np.array([R_C, 0, -R_C, 0]) / R_C ** 2)
F_v7 = np.array([400 * G / 4 * (1 + 2 * 0.100 * x / R_C ** 2) for x in (R_C, 0, -R_C, 0)])
check("S1_модель==формула_v7", np.allclose(F_lin, F_v7, rtol=1e-9),
      f"при e=100мм, k одинаковые: модель {np.round(F_lin,1)} == формуле {np.round(F_v7,1)}")

# 3.2 смещение ЦМ: модель и «84 мм» как её результат
e_loss = {}
for e in (0.0, 0.040, 0.070, 0.084, 0.100, 0.120):
    F = reactions(400, ex=e)
    e_loss[f"{e*1000:.0f}мм"] = {"N_кг": [round(x / G, 1) for x in F],
                                 "min_кг": round(F.min() / G, 1)}
    print(f"  ЦМ+{e*1000:.0f} мм: N={[round(x/G,1) for x in F]} кг "
          f"(min {F.min()/G:.1f})")
# точка нуля модели (ромб R_C): аналитически e = R_C/2 = 110.75 мм
F_a = reactions(400, ex=0.105)
F_b = reactions(400, ex=0.115)
e_zero_model = R_C / 2
# для СЖАТОГО контура (A_G = R_C − W/2): точка нуля = A_G/2 = 84 мм (как в v7)
PTS_G = [p * ((R_C - W_MOD / 2) / R_C) for p in PTS_R]
F_g = reactions(400, ex=0.084, pts=PTS_G)
check("S2_84мм_как_результат_модели",
      F_a.min() > 0 and F_b.min() < 1000 * 9.81,
      f"отрыв в модели при e=R_C/2={e_zero_model*1000:.1f}мм (ромб R_C); "
      f"84мм = A_G/2 для сжатого контура (r_c−W/2): F(e=84мм)={F_g.min()/G:.1f} кг -> "
      f"оба числа — РЕЗУЛЬТАТЫ МОДЕЛЕЙ контура, не универсальные пределы")
print(f"  e_отрыва: ромб R_C -> {e_zero_model*1000:.1f} мм; "
      f"сжатый ромб (A_G) -> {(R_C-W_MOD/2)*1000/2:.1f} мм (v7 смешивал оба контура)")

# 3.3 чувствительность к жёсткости опор
print("  -- чувствительность к жёсткости опор --")
k_cases = {"k_равномерно": (1.0, 1.0, 1.0, 1.0),
           "k_−25%_на_одном": (0.75, 1.0, 1.0, 1.0),
           "k_−50%_на_одном": (0.50, 1.0, 1.0, 1.0),
           "k_разброс_±25%": (1.25, 0.75, 1.25, 0.75)}
k_sens = {}
for name, kk in k_cases.items():
    F = reactions(400, ex=0.060, k_rel=kk)
    k_sens[name] = {"N_кг": [round(x / G, 1) for x in F], "min_кг": round(F.min() / G, 1)}
    print(f"  {name}: N={[round(x/G,1) for x in F]} кг, min={F.min()/G:.1f}")

# 3.4 независимые перемещения подвески / неровности пола
print("  -- неровности пола / перекосы (подъём пола под колесом) --")
h_cases = {"бугор 10мм под колесом0": (0.010, 0.0, 0.0, 0.0),
           "диагональный перекос +5мм": (0.005, 0.0, 0.005, 0.0),
           "уклон 5% по X": None,          # считается отдельно
           "уклон 5% по диагонали": None}
h_sens = {}
F = reactions(400, ex=0.0, h=h_cases["бугор 10мм под колесом0"])
h_sens["бугор10мм_под_колесом0"] = {"N_кг": [round(x / G, 1) for x in F]}
print(f"  бугор 10мм под колесом0: N={[round(x/G,1) for x in F]} кг")
F = reactions(400, ex=0.0, h=h_cases["диагональный перекос +5мм"])
h_sens["диагональный_перекос_5мм"] = {"N_кг": [round(x / G, 1) for x in F]}
print(f"  диагональный перекос +5мм: N={[round(x/G,1) for x in F]} кг")
# уклон 5%: h_i = tan(5°)·(x·cosφ + y·sinφ)
t5 = math.tan(math.radians(5.0 * math.pi / 180)) if False else math.tan(0.05)  # ≈5%
for phi_deg, nm in ((0.0, "по_X"), (45.0, "по_диагонали")):
    ph = math.radians(phi_deg)
    h = tuple(t5 * (p[0] * math.cos(ph) + p[1] * math.sin(ph)) for p in PTS_R)
    F = reactions(400, ex=0.0, h=h)
    h_sens[f"уклон5%_{nm}"] = {"N_кг": [round(x / G, 1) for x in F],
                                "min_кг": round(F.min() / G, 1)}
    print(f"  уклон 5% {nm}: N={[round(x/G,1) for x in F]} кг (min {F.min()/G:.1f})")
print("  Пояснение: плоский уклон при симметричных пружинах НЕ меняет нормальных "
      "реакций (тело наклоняется параллельно) — разгрузка идёт от момента ЦМ "
      "(h_цм·sinα) и от продольных сил (разгон/торможение), см. S3.")
# критический уклон с учётом МОМЕНТА ЦМ (высота ЦМ h_cm): на уклоне tanα
# проекция ЦМ смещается на e ≈ h_cm·sinα; отрыв при e = R_C/2 (в модели).
# Плоский уклон БЕЗ сдвига ЦМ отрыва не даёт (тело наклоняется параллельно
# склону, реакции равны) — отсюда предыдущая ошибка «30%».
H_CM = 0.5          # м — параметр (h_цм не подтверждён)
lo, hi = 0.0, 1.0
for _ in range(50):
    mid = (lo + hi) / 2
    e = H_CM * math.sin(math.atan(mid))     # сдвиг проекции ЦМ вдоль уклона
    F = reactions(400, ex=e)
    if F.min() > 0:
        lo = mid
    else:
        hi = mid
check("S3_уклон_с_моментом_ЦМ", lo > 0.1,
      f"критический уклон (отрыв, модель, 400кг, h_цм={H_CM} м) ≈ {lo*100:.1f}% "
      f"по тангенсу; БЕЗ учёта h_цм отрыва нет (параллельный наклон) — "
      f"h_цм и контур — параметры, не факт")

# 3.5 контуры: переименование
contour = {
    "консервативный_модель_A": {"вершины_ромба_мм": round((R_C - W_MOD / 2) * 1000, 1),
                                "инрадиус_мм": round((R_C - W_MOD / 2) / math.sqrt(2) * 1000, 1),
                                "статус": "КОНСЕРВАТИВНЫЙ по модели (предположение о "
                                          "контакте в пределах r_c−W/2); пятна контакта "
                                          "роликов и подвеска НЕ ПОДТВЕРЖДЕНЫ — "
                                          "термин «гарантированный» отозван"},
    "номинальный": {"вершины_ромба_мм": round(R_C * 1000, 1),
                    "инрадиус_мм": round(R_C / math.sqrt(2) * 1000, 1),
                    "статус": "контакт в центре пятна"},
    "оптимистичный": {"вершины_ромба_мм": round((R_C + W_MOD / 2) * 1000, 1),
                      "инрадиус_мм": round((R_C + W_MOD / 2) / math.sqrt(2) * 1000, 1),
                      "статус": "контакт у внешней кромки"},
}
print("\n== Контуры (переименование) ==")
print(f"  консервативный (модель A): инрадиус {contour['консервативный_модель_A']['инрадиус_мм']} мм "
      f"— «гарантированный» отозван; номинал {contour['номинальный']['инрадиус_мм']} мм")

# 3.6 допустимое смещение рук (пересчёт моделью)
print("  -- допустимое смещение ЦМ при динамике (пересчёт) --")
arm = {}
for hz in (0.5, 0.7):
    for a in (0.5, 1.0):
        b = (R_C - W_MOD / 2) / math.sqrt(2)          # консервативный инрадиус, м
        delta = b - a * hz / G
        arm[f"h={hz},a={a}"] = {"delta_ЦМ_мм": round(delta * 1000, 1)}
        print(f"  h={hz} м, a={a} м/с²: Δ_ЦМ ≤ {delta*1000:.1f} мм (контур-модель A)")

out = {"hold_etalon": hold_etalon, "hold_discrepancy": discrepancy_hold,
       "no_power": no_power, "e_sens": e_loss, "k_sens": k_sens, "h_sens": h_sens,
       "critical_grade_pct": round(lo * 100, 1),
       "contour_terms": contour, "arm_budget": arm, "checks": CHECKS,
       "notes": [
           "84 мм и инрадиус 118.8 — результаты модели (одинаковые k, жёсткая платформа), не пределы.",
           "Модель реакций верифицирована против формулы v7 (PASS S1).",
           "Уклон отрыва и k-характеристики — параметры (подвеска не подтверждена).",
       ]}
path = os.path.join(HERE, "stage2g_v7_1_stability.json")
with open(path, "w", encoding="utf-8") as f:
    json.dump(out, f, ensure_ascii=False, indent=1)
print("\nJSON:", path)
