# -*- coding: utf-8 -*-
"""Этап 2Г, задача 4 — stage2g_v7_mass_stability.py (только Python).

Компонентный массовый бюджет (подтверждённые / параметрические / неизвестные),
диапазоны ЦМ, устойчивость R2 на четырёх колёсах (аутригеры убраны).

КОНСЕРВАТИВНЫЙ опорный контур (пока положение пятен контакта роликов не
подтверждено): контакт может смещаться по радиальной оси модуля в пределах
ширины W=106.9 => гарантированный контур = РОМБ с вершинами на осях колёс
на радиусе a_guar = r_c − W/2 = 168 мм. Номинальный (контакт в центре пятна):
a_nom = r_c = 221.5 мм. Оптимистичный (внешняя кромка): a_opt = r_c + W/2.
Край модуля по радиусу: r_c + W/2 = 274.95 — равен габариту по контуру.
"""
import json
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
G = 9.81

R_C = 221.5          # мм
W_MOD = 106.9        # мм
A_G = R_C - W_MOD / 2.0      # 168.0 — гарантированный ромб
A_N = R_C                    # 221.5 — номинальный (контакт в центре)
A_O = R_C + W_MOD / 2.0      # 274.95 — оптимистичный

# ============ 1. Компонентный массовый бюджет ============
# статус: OK = подтверждено источником; PAR = параметр (диапазон обоснован/нет);
# UNK = неизвестно, требуется запрос/данные
BUDGET = [
    ("Колёсные модули 4×25 кг (с амортизатором)", 100.0, 100.0, "OK",
     "RoboCT: 25 кг/wheel (обе страницы); industrial: 10 кг без амморт."),
    ("Панель Ø620×40 (сталь / алюминий, с вырезами ниш)", 45.0, 76.0, "PAR",
     "расчёт по объёму; материал НЕ ВЫБРАН; сталь 7850/алюм 2700 кг/м³"),
    ("Механизм лифта (бюджет подъёма ≥500 кг, стойка+привод)", 30.0, 90.0, "UNK",
     "концепция лифта не выбрана; масса типовых ЛПР 30-90 кг — оценка 🔴"),
    ("Аутригеры 4× (телескоп 2 ступени, ход 300, площадка)", 20.0, 64.0, "UNK",
     "5-16 кг на блок — оценка 🔴; от 300 кг г/п требуемая прочность не расчитана"),
    ("АКБ (24-48 В, ёмкость под 4 мотора + лифт)", 20.0, 45.0, "UNK",
     "энергобюджет не рассчитан (сценарий смены не задан) 🔴"),
    ("Приводы/контроллеры/проводка", 8.0, 18.0, "UNK", "оценка 🔴"),
    ("Кабина 1100×2100 (каркас, пол, стены — как часть лифта)", 40.0, 120.0, "UNK",
     "конструкция кабины не прорабатывалась 🔴"),
    ("Манипуляторы/оборудование (транспортное положение)", 0.0, 150.0, "UNK",
     "СОСТАВ НЕ ЗАДАН — главный неизвестный 🔴"),
]
tot_lo = sum(b[1] for b in BUDGET)
tot_hi = sum(b[2] for b in BUDGET)
print("== 1. Компонентный массовый бюджет ==")
print(f"{'компонент':<58} {'кг':>12} {'статус':>6}")
for name, lo, hi, st, note in BUDGET:
    rng = f"{lo:.0f}" if lo == hi else f"{lo:.0f}-{hi:.0f}"
    print(f"  {name:<56} {rng:>12} {st:>6}")
print(f"  {'ИТОГО':<56} {f'{tot_lo:.0f}-{tot_hi:.0f}':>12}")
print("  Оценка 300-450 кг (из v3) не подтверждена — считать диапазоном для расчёта, не фактом.")
MASS_RANGE = (max(tot_lo, 300.0), min(tot_hi, 450.0)) if tot_lo < 450 else (tot_lo, tot_hi)
print(f"  Рабочий диапазон для расчётов: {MASS_RANGE[0]:.0f}-{MASS_RANGE[1]:.0f} кг 🔴/⬛")

# ============ 2. ЦМ: транспортное положение (лифт и манипуляторы убраны) ============
# z-уровни компонентов из v6-компоновки (панель 50-90, модули ось z=120, АКБ 92-192...)
CM_CASES = {
    "низкий (без кабины/манипуляторов, АКБ внизу)": (250.0, 400.0),
    "средний (кабина на лифте, руки сложены)": (400.0, 600.0),
    "высокий (поднятое оборудование, руки вверху)": (600.0, 850.0),
}
print("\n== 2. Диапазоны ЦМ по высоте (транспорт, параметры) ==")
for k, v in CM_CASES.items():
    print(f"  {k}: h_цм = {v[0]:.0f}..{v[1]:.0f} мм 🔴 (нет масс/высот по отдельности)")

# ============ 3. Опорный контур и статика ============
print("\n== 3. Опорный контур (ромб, контакт не подтверждён) ==")
for tag, a in (("гарантированный (r_c−W/2)", A_G), ("номинальный (r_c)", A_N),
               ("оптимистичный (r_c+W/2)", A_O)):
    inrad = a / math.sqrt(2.0)
    print(f"  {tag}: вершины ±{a:.1f} мм, инрадиус {inrad:.1f} мм, "
          f"площадь {2*a*a/1e6:.4f} м²")

# статический угол опрокидывания по 4 направлениям (худшее — перпендикуляр ребру)
def tip_angles(a, h):
    """Угол опрокидывания по направлению наименьшего выноса (к ребру ромба)."""
    b = a / math.sqrt(2.0)          # расстояние от центра до ребра
    return math.degrees(math.atan(b / h))

print("\n== 4. Статика: угол опрокидывания (аутригеры убраны) ==")
stat = {}
for tag, a in (("гарант", A_G), ("номинал", A_N)):
    for h in (400.0, 500.0, 700.0):
        ang = tip_angles(a, h)
        stat[f"{tag}_h{h:.0f}"] = round(ang, 1)
print("  h_цм, мм | гарант(α) | номинал(α)   [α=atan(b/h), b=инрадиус ромба]")
for h in (400.0, 500.0, 700.0):
    print(f"  {h:8.0f} | {tip_angles(A_G,h):9.1f}° | {tip_angles(A_N,h):8.1f}°")

# ============ 5. Динамика: разгон/торможение/поворот ============
print("\n== 5. Динамика (предел a = g·b/h; b к ребру ромба) ==")
dyn = {}
for tag, a in (("гарант", A_G), ("номинал", A_N)):
    b = a / math.sqrt(2.0)
    for h in (500.0, 700.0):
        at = G * b / 1000.0 / (h / 1000.0)
        dyn[f"{tag}_h{h:.0f}"] = round(at, 2)
        print(f"  {tag}, h={h:.0f}: a_опрок={at:.2f} м/с²")
# сравнение с пределом сцепления из dynamics: 1.94..4.16
print("  сцепление (сух.худ 1.94 / луч 4.16 м/с²) vs опрокидывание:")
print(f"   гарант h=500: {G*A_G/math.sqrt(2)/1000/0.5:.2f} — меньше худшего сцепления (ограничивает)")
print(f"   гарант h=700: {G*A_G/math.sqrt(2)/1000/0.7:.2f} — опрокидывание первым при лучшем сцеплении")
# поворот (центробежный)
v = 0.7
for R_min in (0.5, 1.0):
    a_c = v * v / R_min
    print(f"  поворот v=0.7, R={R_min} м: a_центробр={a_c:.2f} м/с² "
          f"против опрок h=700 гарант {G*A_G/math.sqrt(2)/1000/0.7:.2f}")

# ============ 6. Потеря контакта одного колеса ============
print("\n== 6. Потеря контакта одного колеса ==")
# при ЦМ в центре: оставшийся треугольник — ребро противоположного выреза проходит через центр
loss = {
    "ЦМ_в_центре": "запас 0: ЦМ лежит НА ребре оставшегося треугольника (всегда, для 4-точечной симметрии)",
    "требование_компенсации": "запас >0 только при выносе ЦМ внутрь оставшегося треугольника",
    "мин_вынос_ЦМ": "любое смещение ЦМ к выжившим 3 колёсам; к утраченному — мгновенное опрокидывание",
    "динамика_потери": "а=0.5 м/с² перенос 23 кг (из dynamics) — при N_мин=7-10 кг (e=100мм) контакт ЛЕГКО теряется",
}
for k, v in loss.items():
    print(f"  {k}: {v}")

# ============ 7. Допустимое движение рук во время движения ============
print("\n== 7. Допустимое смещение рук/оборудования во время движения ==")
budget = {}
for h in (500.0, 700.0):
    for a_dyn in (0.5, 1.0):
        # запас до опрокидывания: b_eff = a·g/ω... допустимый вынос ЦМ: Δ < b − a_dyn·h/g
        for tag, a in (("гарант", A_G), ("номинал", A_N)):
            b = a / math.sqrt(2.0)
            delta = b - a_dyn * (h / 1000.0) / G * 1000.0   # b в мм; a·h/g в м -> мм
            key = f"{tag}, h={h:.0f}, a={a_dyn}"
            budget[key] = {"допустимый_вынос_ЦМ_мм": round(delta, 1),
                           "вердикт": "допустимо" if delta > 0 else "НЕДОПУСТИМО (только статика)"}
            print(f"  {tag}, h={h:.0f}, a={a_dyn} м/с²: Δ_ЦМ ≤ {delta:.1f} мм "
                  f"{'OK' if delta > 0 else '— опрокидывание раньше!'}")

# ============ 8. Против 250 кг/колесо ============
print("\n== 8. Предел 250 кг/колесо (паспорт) ==")
for M in (300.0, 400.0, 450.0):
    # N_max = M/4·(1+2e/a) => e_прев = a/2·(250·4/M − 1); потеря контакта всегда при e = a/2
    e_loss = A_G / 2.0
    e_over = A_G / 2.0 * (250.0 * 4.0 / M - 1.0)
    print(f"  M={M:.0f} кг: потеря контакта противоположного колеса при e ≥ {e_loss:.0f} мм; "
          f"превышение 250 кг при e ≥ {e_over:.0f} мм "
          f"{'(контакт потеряется раньше, чем превысится 250 кг)' if e_over > e_loss else ''}")

# ============ Сохранение ============
out = {"budget": [{"name": b[0], "lo": b[1], "hi": b[2], "status": b[3], "note": b[4]}
                  for b in BUDGET],
       "total_range": [round(tot_lo, 1), round(tot_hi, 1)],
       "mass_working_range": [MASS_RANGE[0], MASS_RANGE[1]],
       "cm_z_cases": {k: list(v) for k, v in CM_CASES.items()},
       "contour": {"guaranteed_rhomb": A_G, "nominal_rhomb": A_N, "optimistic_rhomb": A_O,
                   "inradius_guar": round(A_G / math.sqrt(2), 1),
                   "inradius_nom": round(A_N / math.sqrt(2), 1)},
       "tip_angles_deg": stat, "dynamic": dyn,
       "single_wheel_loss": loss, "arm_motion_budget": budget,
       "notes": [
           "Опорный контур — ромб по осям модулей; пятна контакта роликов НЕ подтверждены.",
           "Гарантированный контур (r_c−W/2) — для консервативной оценки до чертежей подвески.",
           "h_цм и разброс по отдельным компонентам НЕ ИЗВЕСТНЫ — диапазоны параметрические.",
           "Потеря одного колеса при ЦМ в центре: нулевой статический запас (общее свойство 4-точечной симметрии).",
           "Конструкция НЕ объявлена безопасной: массы, ЦМ, динамика рук — не подтверждены.",
       ]}
path = os.path.join(HERE, "stage2g_v7_mass_stability.json")
with open(path, "w", encoding="utf-8") as f:
    json.dump(out, f, ensure_ascii=False, indent=1)
print("\nJSON:", path)
