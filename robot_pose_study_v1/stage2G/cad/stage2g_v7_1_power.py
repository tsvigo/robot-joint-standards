# -*- coding: utf-8 -*-
"""Этап 2Г, аудит v7.1 — stage2g_v7_1_power.py (только Python, НОВЫЙ файл).

Задача 1: сопоставление ТРЁХ официальных страниц RoboCT для CTM1000-10R и
механическая/электрическая мощность в КАЖДОЙ заявленной рабочей точке.

Страницы (источники SearXNG, извлечение в этом аудите):
  P1 "Heavy Duty Mecanum Wheel":      220-440 Вт, IP44, 24-48 В, 74 Н·м, 56 об/мин, 4096 lines, 25 кг
  P2 "Industrial Mecanum Wheel":       180 Вт, IP54, 48 В, мотор 2 Н·м BEP / 4 Н·м пик / 3000 об/мин,
                                       10 кг без амморт / ~25 кг, 4096 wires
  P3 "Heavy Duty Mecanum Wheel Module": 24/36/48 В; 220/330/440 Вт; КПД 70/75/76%;
                                       ном. скорости 28/43/56 об/мин; 74 Н·м; пик 140 Н·м;
                                       ном. 1000 кг / макс 1200 кг; 4384 line; токи 12.8/12.9/13 А;
                                       no-load 36/54/72 об/мин; КПД редуктора нет; P_out = P_elec·η

Расчёт: P_out = τ·ω для каждой точки; три независимых оценки входной мощности:
  (a) P_in = U·I (по токам страницы),
  (b) P_in = P_out/η (по КПД страницы),
  (c) P_in ≈ Rated Power (если «мощность» — электрическая — проверка на абсурд η>100%).
Все три сверяются; расхождения фиксируются как материал запроса.
"""
import json
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
TAU_RATED = 74.0
TAU_PEAK_P3 = 140.0
I_GEAR = 37.1

# точки P3: (U, RatedPower_W, eta, n_out_rpm, I_A, n_noload_rpm)
PTS = [
    ("24В", 24.0, 220.0, 0.70, 28.0, 12.8, 36.0),
    ("36В", 36.0, 330.0, 0.75, 43.0, 12.9, 54.0),
    ("48В", 48.0, 440.0, 0.76, 56.0, 13.0, 72.0),
]

rows = []
print("== Рабочие точки CTM1000-10R (страница P3) ==")
print(f"{'точка':>5} {'P_out=τω':>9} {'Rated':>6} {'Δ%':>5} | "
      f"{'P_in=U·I':>9} {'η_calc':>7} {'η_стр':>6} | {'P_in=P_out/η':>13} {'I_нужно':>8}")
for tag, U, P_rated, eta, n, I, _n0 in PTS:
    w = n * 2 * math.pi / 60.0
    P_out = TAU_RATED * w
    d_p = (P_rated - P_out) / P_out * 100.0
    P_in_ui = U * I
    eta_calc = P_out / P_in_ui
    P_in_eta = P_out / eta
    I_need = P_in_eta / U
    rows.append({
        "точка": tag, "U_В": U, "n_out_об_мин": n, "P_out_Вт": round(P_out, 1),
        "RatedPower_Вт": P_rated, "delta_Rated_vs_Pout_%": round(d_p, 1),
        "P_in_UI_Вт": round(P_in_ui, 1), "eta_calc": round(eta_calc, 3),
        "eta_стр": eta, "P_in_по_eta_Вт": round(P_in_eta, 1),
        "I_нужно_А": round(I_need, 1), "I_стр_А": I,
        "eta_при_Rated_как_электр": round(P_out / P_rated, 3),
    })
    print(f"{tag:>5} {P_out:9.1f} {P_rated:6.0f} {d_p:+5.1f} | "
          f"{P_in_ui:9.1f} {eta_calc:7.3f} {eta:6.2f} | {P_in_eta:13.1f} {I_need:8.1f}")

# ============ Выводы по трактовке ============
print("\n== Трактовка «Rated Power» ==")
for r in rows:
    print(f"  {r['точка']}: если Rated — ЭЛЕКТРИЧЕСКАЯ: η = {r['eta_при_Rated_как_электр']:.3f} "
          f"{'<< абсурд (>0.95)' if r['eta_при_Rated_как_электр'] > 0.95 else ''}")
treat = {
    "Rated_220_330_440": ("≈ P_out (217/333/434 Вт, отклонение ≤1.4%) =>Rated Power заявлена "
                          "как МЕХАНИЧЕСКАЯ выходная (или эквивалент); электрическая входная "
                          "выше: 307-624 Вт по токам / 310-571 Вт по η"),
    "абсурд_проверка": "η>95% при электрической трактовке — невозможно (КПД 70-76% заявл.)",
    "180Вт_P2": ("несовместим с 74 Н·м×56 об/мин при ЛЮБОЙ трактовке: "
                 "как выход 180<434; как вход при η=0.7-0.76 => выход 126-137 «втрое меньше». "
                 "Также 180 Вт < P_out BEP-мотора P2 (2 Н·м×3000 об/мин = 628 Вт) — "
                 "внутреннее противоречие самой страницы P2"),
}
for k, v in treat.items():
    print(f"  {k}: {v}")

# ============ Сопоставление всех трёх страниц ============
def cmp_row(name, p1, p2, p3, verdict):
    return {"параметр": name, "P1_heavy": p1, "P2_industrial": p2, "P3_module": p3,
            "вывод": verdict}

CMP = [
    cmp_row("Мощность", "220-440 Вт", "180 Вт", "220/330/440 Вт (по 24/36/48 В)",
            "P3 уточняет: по напряжениям; ≈выходная. P2 противоречит (🔴)"),
    cmp_row("IP", "IP44", "IP54", "не указано", "🔴 IP44 vs IP54 не разрешено"),
    cmp_row("Напряжение", "24-48 В", "48 В", "24/36/48 В", "P3 согласуется с P1; P2 — только 48 🟡"),
    cmp_row("Ном. момент", "74 Н·м", "2 Н·м BEP×37.1=74.2 (вывод)", "74 Н·м", "✅ согласовано"),
    cmp_row("Пик. момент", "не указано", "4 Н·м×37.1≈148.4 (вывод, без потерь)",
            "140 Н·м (вывод)",
            "🟡 140 vs 148: отношение 0.943 => объяснимо η_редуктора≈94% на пике; "
            "или 140 — уточнение. Сверить в запросе"),
    cmp_row("Скорость", "56 об/мин", "3000 об/мин мотора => 80.9 вых. холостая",
            "28/43/56 об/мин (холостая 36/54/72)",
            "🔴 холостая: 80.9 (P2) vs 72 (P3) при 48 В — расхождение 12%"),
    cmp_row("Энкодер", "4096 Wire", "4096 Wire", "4384 Line",
            "🔴 4096 vs 4384 — прямое противоречие; 4384 не степень двойки — спросить"),
    cmp_row("Нагрузка", "1000 кг (комплект)", "1000 кг (комплект)",
            "ном. 1000 / макс 1200 кг (комплект)",
            "🟡 P3 вводит максимум 1200 (300 кг/колесо) — новый факт; "
            "динамический множитель не раскрыт"),
    cmp_row("Масса", "25 кг/колесо", "10 кг без амморт / ~25 кг с ним", "не указано",
            "🟡 ~25 кг с подвеской; полный монтажный габарит не ясен"),
    cmp_row("КПД", "не указано", "не указано", "70/75/76 %",
            "🟢 только P3: η растёт с U; η_calc по токам: 0.706/0.717/0.696 "
            "-> для 24 В точно (0.706≈0.70), для 36/48 В расхождение 3-6 п.п. 🔴"),
]
print("\n== Сопоставление страниц ==")
for c in CMP:
    print(f"  {c['параметр']}: {c['вывод']}")

# ============ Скорость платформы по каждой точке ============
print("\n== Скорость платформы R2 (v = ω·r, r=0.12 м; MIT-связь v=ω·r_eff/cos45° = ω·r) ==")
speeds = {}
for tag, U, P_rated, eta, n, I, n0 in PTS:
    speeds[tag] = {"v_ном_м_с": round(n / 60 * 2 * math.pi * 0.12, 3),
                   "v_холост_м_с": round(n0 / 60 * 2 * math.pi * 0.12, 3)}
    print(f"  {tag}: v_ном={speeds[tag]['v_ном_м_с']} м/с, "
          f"v_холостая={speeds[tag]['v_холост_м_с']} м/с (P2-холостая: "
          f"{3000/I_GEAR/60*2*math.pi*0.12:.3f} м/с — расхождение с P3)")

# ============ Пиковый момент ============
print("\n== Пиковый момент ==")
peak = {"расчёт_без_потерь_Нм": 4.0 * I_GEAR,
        "P3_заявлено_Нм": TAU_PEAK_P3,
        "отношение": round(TAU_PEAK_P3 / (4.0 * I_GEAR), 3),
        "объяснение": "140/148.4 = 0.943 — согласуется с η_редуктора ≈94% (или уточнение); спросить длительность пика"}
print(f"  4 Н·м×37.1 = {peak['расчёт_без_потерь_Нм']} Н·м; P3: {TAU_PEAK_P3} Н·м; "
      f"отношение {peak['отношение']} -> {peak['объяснение']}")

# ============ Ошибка v7 в功率 ============
v7_error = {
    "было_v7": ("«440 Вт согласуются (≥493 Вт при η=0.88)» — два нарушения: "
                "(1) η=88% не заявлен (заявлено 70-76%); (2) 493 Вт — требуемые "
                "ЭЛЕКТРИЧЕСКИЕ входные, а «440» по P3 — выходные: сравнение разных величин."),
    "стало_v7_1": ("Согласование точек: P_out(48В) = 434 Вт ≤ Rated 440 Вт (Δ=1.4%) — "
                   "механически согласовано; электрический вход = 571 Вт (по η=76%) "
                   "или 624 Вт (U·I=48×13) — источник питания должен быть ≥624 Вт на мотор; "
                   "внутри страницы P3 спор между η- и ток-методами = 3-9% — в запрос."),
}
print("\n== Исправление ошибки v7 (мощность) ==")
print(" ", v7_error["было_v7"])
print(" ", v7_error["стало_v7_1"])

out = {"points": rows, "comparison": CMP, "speeds": speeds, "peak": peak,
       "treatment": treat, "v7_error_fix": v7_error,
       "notes": [
           "Источники: 3 страницы roboct-global.com (P1/P2/P3), извлечено в аудите v7.1.",
           "P3-данные: 24/36/48В, 220/330/440Вт, η70/75/76%, 28/43/56об/мин, 140Н·м пик, 1200кг макс, 4384 line, токи 12.8/12.9/13А.",
           "Расхождения P3 (токи vs η vs Rated) 0-9% — не разрешить без производителя.",
       ]}
path = os.path.join(HERE, "stage2g_v7_1_power.json")
with open(path, "w", encoding="utf-8") as f:
    json.dump(out, f, ensure_ascii=False, indent=1)
print("\nJSON:", path)
