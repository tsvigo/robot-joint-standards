def r2(p):
    """Мировая СК Blender -> СК R2 (м)."""
    return (p[0] - OX, p[1] - OY, p[2] - FLOOR_Z)


def group_com(pred):
    """Масса и взвешенный origin (допущение COM=origin) для объектов с mass."""
    ms, xs, ys, zs = 0.0, 0.0, 0.0, 0.0
    n = 0
    for name, v in OBJS.items():
        m = v.get("mass")
        if not m or not pred(name):
            continue
        p = v.get("matrix_world_translation")
        if not p:
            continue
        q = r2(p)
        ms += m; xs += m * q[0]; ys += m * q[1]; zs += m * q[2]; n += 1
    if ms == 0:
        return None
    return {"m": round(ms, 3), "com": [round(xs / ms, 3), round(ys / ms, 3),
                                       round(zs / ms, 3)], "n": n}


