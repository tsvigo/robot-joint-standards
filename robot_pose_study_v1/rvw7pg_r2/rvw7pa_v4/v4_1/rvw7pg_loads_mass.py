"""
Stage 2G — нагрузки на входной вал RVW-7PG, тяга и баланс масс.

1) Нагрузка на входной вал Ø14 при вынесенном моторе (3 схемы).
   Допустимая радиальная/осевая нагрузка каталогом НЕ приведена (UNK) ->
   расчёт даёт ТРЕБОВАНИЕ к опоре, а не подтверждение прочности.
2) Тяга: RVW-7 серия (7 Н·м) против RoboCT (74 Н·м) — по данным v4.
3) Баланс масс: M_new = M_old - M_removed + M_added (со всеми UNK явно).
4) Ограничение лифта 500 кг и рекомендация Nabtesco 200 кгс x 4 x 3/4 = 600 кг.

FEA, тепловой расчёт и деталировка НЕ выполняются.
"""

import json
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
CHECKS = []
OUT = {}


def t(cid, ok, detail):
    CHECKS.append({"id": cid, "ok": bool(ok), "detail": detail})
    print(f"  [{'PASS' if ok else 'FAIL'}] {cid}: {detail}")


# ============ 1. Входной вал =================================================
G = 9.81
SHAFT_D = 14.0                       # мм, Ø14H7 (каталог, стр.22)
SHAFT_L = 32.0                       # мм, вылет L (каталог, стр.22)
T_IN_RATED = {"200W": 0.637, "400W": 1.27}      # Н·м, момент мотора
T_IN_MAX = {"200W": 1.34, "400W": 2.54}         # Н·м, моментный максимум
PULLEY_D = 40.0                      # мм, ПАРАМЕТР (подбор ремня/пары)

print("== 1. Нагрузка на входной вал Ø14 при вынесенном моторе ==")
shaft = {}
for sch, note in (("A_ремень", "ремень: F = 2*T/(d_шкива), две ветви"),
                  ("B_зубчатая_пара", "пара: окружное усилие F = T/(d_дел/2)"),
                  ("C_угловая", "угловой редуктор: то же окружное усилие + осевая составляющая")):
    shaft[sch] = {}
    for m, T in T_IN_RATED.items():
        F = 2.0 * T / (PULLEY_D / 1000.0)          # Н, суммарное натяжение
        M = F * (SHAFT_L / 1000.0)                 # Н·м, изгибающий момент на вылете
        sigma = 32.0 * M / (math.pi * (SHAFT_D / 1000.0) ** 3) / 1e6   # МПа
        Fmax = 2.0 * T_IN_MAX[m] / (PULLEY_D / 1000.0)
        shaft[sch][m] = {"T_вход_Нм": T, "F_силы_Н": round(F, 1),
                         "M_на_вылете_Нм": round(M, 2),
                         "sigma_МПа_ОТОЗВАНО": round(sigma, 1),
                         "статус_sigma": "ОТОЗВАНО как неподтверждённый: расчёт "
                                         "строен на сплошном вале Ø14x32, а Ø14H7 — "
                                         "это ОТВЕРСТИЕ входного элемента; "
                                         "фактический входной узел и его сечение "
                                         "не соответствуют модели",
                         "F_моментный_Н": round(Fmax, 1)}
        print(f"  {sch} {m}: T_вх={T} Н·м -> F≈{F:.0f} Н, "
              f"M на вылете {M:.2f} Н·м (моментный F≈{Fmax:.0f} Н); "
              f"σ≈{sigma:.1f} МПа — ОТОЗВАНО, неподтверждено")
    print(f"    примечание: {note}")

OUT["входной_вал"] = {
    "параметры": {"Ø_вала_мм": SHAFT_D, "вылет_мм": SHAFT_L,
                  "Ø_шкива_мм": PULLEY_D,
                  "статус_допустимых_нагрузок":
                      "UNK — Nabtesco не публикует допустимую радиальную/осевую "
                      "нагрузку на входной вал RVW-7PG"},
    "расчёт": shaft,
    "вывод": ("Расчёт даёт ТРЕБОВАНИЕ, а не допуск: реакция на вылете Ø14-вала "
              "(изгибающий момент от натяжения) должна восприниматься "
              "НЕЗАВИСИМОЙ опорой промежуточного вала, а не редуктором. "
              "Считать допустимыми радиальные нагрузки на входной вал нельзя — "
              "данных в каталоге нет."),
    "схемы": {
        "A_ремень": "нужен промежуточный вал на 2 подшипниках либо натяжной "
                    "ролик, воспринимающий натяжение (кроме опоры на моторе)",
        "B_зубчатая_пара": "нужен отдельный корпус с 2 подшипниками промежуточного "
                           "вала; центровое расстояние жёстко, требуется точность "
                           "сопряжения; шум и износ выше ремня",
        "C_угловая": "корпус угловой передачи воспринимает момент от phảnакции — "
                     "нужна опора, снимаяющая изгибающий момент с входного вала",
    },
}
t("L1_входной_вал", True,
  "допустимые нагрузки на входной вал в каталоге отсутствуют (UNK) -> "
  "для всех трёх схем требуется независимая опора промежуточного вала")

# ============ 2. Тяга ========================================================
print("\n== 2. Тяга: 7 Н·м против 74 Н·м (данные rvw7pa_drive_check.json) ==")
v4 = os.path.join(os.path.dirname(HERE), "rvw7pa_drive_check.json")
drive = json.load(open(v4, encoding="utf-8"))
mom = drive["моменты"]
T_RATED_RVW, T_RATED_ROBOCT = 7.0, 74.0
R_RVW, R_ROBOCT = 0.089, 0.120          # м: Ø178 и Ø240
# для ОДНОЙ И ТОЙ ЖЕ требуемой окружной силы момент пропорционален радиусу.
# Масштабировать 74/7 НЕЛЬЗЯ — это разные величины (см. отчёт v4.1).
rows = []
for M in (300.0, 400.0, 450.0):
    for gr in (0.0, 5.0, 8.0):
        for d in ("X", "диагональ"):
            r = [x for x in mom if x["масса_кг"] == M and x["уклон_%"] == gr
                 and x["a_м_с2"] == 0.0 and x["направление"] == d]
            if not r:
                continue
            tv = r[0]["T_колеса_Нм"]
            tr = tv * (R_ROBOCT / R_RVW)               # RoboCT: та же окружная сила
            rows.append({"M": M, "уклон_%": gr, "направление": d,
                         "T_RVW_Нм": tv, "%_от_7": round(100 * tv / T_RATED_RVW),
                         "статус_RVW": "PASS" if tv <= T_RATED_RVW else "FAIL",
                         "T_RoboCT_Нм": round(tr, 2),
                         "%_от_74": round(100 * tr / T_RATED_ROBOCT),
                         "масштаб_радиус": round(R_ROBOCT / R_RVW, 3)})
            print(f"  {M:.0f} кг {gr:.0f}% {d:<9}: RVW {tv:5.2f} Н·м "
                  f"({100*tv/7:5.1f}% от 7) -> {'PASS' if tv<=7 else 'FAIL'}; "
                  f"RoboCT {tr:5.2f} Н·м ({100*tr/74:4.1f}% от 74)")

n_pass = sum(1 for r in rows if r["статус_RVW"] == "PASS")
print(f"  итог RVW-7: PASS {n_pass}/{len(rows)} режимов")
t("L2_тяга_RVW", n_pass < len(rows),
  f"RVW-7 серия (7 Н·м) проходит только {n_pass}/{len(rows)} режимов; "
  f"базовый (300 кг, 5 %, вдоль X) = "
  f"{[r['T_RVW_Нм'] for r in rows if r['M']==300 and r['уклон_%']==5 and r['направление']=='X'][0]} Н·м "
  f"= 93 % от 7 — уже на пределе, диагональ — FAIL")
OUT["тяга"] = {"режимы": rows, "T_RVW_Нм": T_RATED_RVW, "T_RoboCT_Нм": T_RATED_ROBOCT,
               "PASS_из": [n_pass, len(rows)],
               "важно": "T_RoboCT = T_RVW x (0.120/0.089) — ОДНА И ТА ЖЕ окружная "
                        "сила; масштаб 74/7 = 10.57 НЕ применяется (это отношение "
                        "номинальных моментов, а отношение окружных сил 7.84)"}

# ============ 3. Баланс масс =================================================
print("\n== 3. Баланс масс: M_new = M_old - M_removed + M_added ==")
ROBOCT_4 = 100.0          # 4 x 25 кг — ПОДТВЕРЖДЕНО паспортом
# RVW-7PG — РАЗДЕЛЬНЫЙ учёт, а не одним числом 61.6 кг:
RVW_GEARBOX_4 = 4 * 12.0  # 4 x 12 кг (guideline каталога: колесо+редуктор+фланец)
RVW_MOTOR_4 = 4 * 3.4     # ВЫВОД = actuator 15.4 - gearbox 12.0; в каталоге отдельно НЕТ
RVW_TRANSMISSION_4 = None # UNK: ремень/шкипы/шестерни + корпус + подшипники
RVW_BRAKE = None          # UNK: тормоз в каталоге указан для ДВИГАТЕЛЯ актёра,
                          # на вынесенный мотор PG не переносится автоматически
RVW_SUSPENSION = None     # UNK: подвески у PG нет
RVW_MOUNTS_4 = 2.4        # хомуты (расчёт v4)
PANEL = 18.4              # ВЫЧЕТ НЕ ПОДТВЕРЖДЁН: пересечение рамы и панели есть,
                          # но состав заменяемой конструкции не подтверждён
                          # (панель в FCStd = 10.78 кг Al, в stage2G = 18.4 кг)
SPACER = 2.0              # проставка 31 мм
FRAME_RING = 5.0          # рама v4 с кольцом и постами (v4.1)
FRAME_RAISED = 5.0        # масса рамы при переносе в z 134..176 — ПАРАМЕТР (пересчёт)
CLAMPS = 2.4
LIFT_LIMIT = 500.0
UNKNOWNS = {"передат_механизм_4x": "UNK (ремень/пара/угловой редуктор + корпус + опоры)",
            "тормоз": "UNK — тормоз RVW-7PA (0.637/1.27 Н·м) к PG с вынесенным "
                      "мотором НЕ переносится автоматически; тип и место тормоза "
                      "для вынесенного мотора не определены",
            "подвеска": "UNK (узел не спроектирован)",
            "внешние_моторы": "масса выводится как 15.4-12.0 = 3.4 кг — ВЫВОД, "
                              "не паспортное значение",
            "кронштейны_и_проводка": "UNK",
            "состав_старой_панели": "НЕ ПОДТВЕРЖДЁН — вычитание 18.4 кг требует "
                                    "подтверждённого состава заменяемой конструкции",
            "рама_после_переноса": "параметр (5.0 кг — для рамы z 60..90)"}

balance = []
for total in (380.0, 480.0, 530.0):     # робот+груз + 80 кг человек = 530 и т.д.
    load = total - 80.0
    new = (total - ROBOCT_4 - PANEL + RVW_GEARBOX_4 + RVW_MOTOR_4
           + SPACER + FRAME_RING + CLAMPS)   # без UNK-компонентов
    margin = LIFT_LIMIT - new
    balance.append({"итого_для_лифта_кг": total, "робот_с_грузом_кг": load,
                    "после_замены_кг": round(new, 1),
                    "запас_до_500_кг": round(margin, 1),
                    "статус": "FAIL" if new > LIFT_LIMIT else
                              ("CONDITIONAL" if margin < 40 else "PASS")})
    print(f"  {total:.0f} кг (робот {load:.0f} + 80 человек) -> {new:.1f} кг; "
          f"запас до 500 = {margin:.1f} кг -> "
          f"{'FAIL' if new>LIFT_LIMIT else ('CONDITIONAL' if margin<40 else 'PASS')}")

print("  неизвестные, вычитаемые из запаса:")
for k, v in UNKNOWNS.items():
    print(f"    {k}: {v}")
OUT["баланс_масс"] = {"состав": {
        "снимается": {"RoboCT_4x25": ROBOCT_4,
                      "панель": PANEL,
                      "оговорка_по_панели": "вычет 18.4 кг НЕ подтверждён: "
                                             "пересечение с рамой доказывает только "
                                             "конфликт объёмов, а не состав"},
        "добавляется_раздельно": {
            "редуктор_и_колёса_PG_4x12": RVW_GEARBOX_4,
            "внешние_моторы_4x3.4_ВЫВОД": RVW_MOTOR_4,
            "проставка": SPACER, "рама": FRAME_RING, "хомуты": CLAMPS},
        "сумма_только_из_подтверждённого": round(RVW_GEARBOX_4 + RVW_MOTOR_4
                                                 + SPACER + FRAME_RING + CLAMPS, 1),
        "неизвестные": UNKNOWNS},
                      "формула": ("M_new = M_old - 100(модули RoboCT) - 18.4(панель, "
                                  "вычет НЕ подтверждён) + 48.0(редуктор+колёса PG) "
                                  "+ 13.6(моторы, ВЫВОД) + 2.0 + 5.0 + 2.4 "
                                  "+ передача/тормоз/подвеска/крепления = UNK"),
                      "61_6_не_подтверждено": ("61.6 кг = 4 x 15.4 кг — это масса "
                                               "АГРЕГАТА 7PA с ВСТРОЕННЫМ мотором. "
                                               "Для PG с вынесенным мотором это НЕ "
                                               "подтверждённая масса четырёх полных "
                                               "приводов: к ней добавляются передача, "
                                               "тормоз, подвеска и крепления (все UNK)"),
                      "сценарии": balance,
                      "вывод": ("Пересечение рамы и панели (1 186 165 мм³, зазор "
                                "0.000 мм) доказывает ТОЛЬКО конфликт занимаемых "
                                "объёмов — оно НЕ доказывает, что все 18.4 кг можно "
                                "вычесть: нужен подтверждённый состав заменяемой "
                                "конструкции. Итог 482.6 кг и запас 17.4 кг до "
                                "лимита 500 кг — НЕ окончательные: масса моторов "
                                "выведена, передача/тормоз/подвеска/крепления не "
                                "учтены.")}

# ============ 4. Рекомендация Nabtesco ======================================
print("\n== 4. Рекомендация Nabtesco: 200 кгс x 4 x 3/4 = 600 кг ==")
rec = 200.0 * 4 * 0.75
for load in (300.0, 400.0, 450.0, 530.0):
    ok = load <= rec
    print(f"  робот+груз {load:.0f} кг <= {rec:.0f} кг -> {'PASS' if ok else 'FAIL'}; "
          f"на колесо в покое {load/4:.1f} кг при допуске 200 кгс")
OUT["nabtesco_600kg"] = {"рекомендация_кг": rec,
                       "проверка": [{"нагрузка_кг": x, "PASS": x <= rec}
                                    for x in (300.0, 400.0, 450.0, 530.0)]}
t("L3_nabtesco", 450.0 <= rec,
  "450 кг (робот+груз) укладывается в рекомендацию 600 кг; с человеком 530 кг "
  "тоже укладывается, но превышает лимит лифта 500 кг")

OUT["контрольные_точки"] = CHECKS
with open(os.path.join(HERE, "rvw7pg_loads_mass.json"), "w", encoding="utf-8") as fh:
    json.dump(OUT, fh, ensure_ascii=False, indent=2, default=str)
bad = [c for c in CHECKS if not c["ok"]]
print(f"\n== ИТОГ: проверок {len(CHECKS)}, провалено {len(bad)} ==")