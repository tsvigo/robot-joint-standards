def F_vec_450(a, grade, direction=(1.0, 0.0)):
    """Сила сопротивления/тяги (формула каталога, вдоль direction):
    M·(a + g·(sinθ + Crr·k_mec·cosθ)) — с cosθ у трения на склоне."""
