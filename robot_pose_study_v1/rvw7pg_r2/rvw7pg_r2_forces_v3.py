TH = [0.0, 90.0, 180.0, 270.0]
SIG = (1, 1, 1, 1)


def jacobian(Rw=RW):
    J = np.zeros((4, 3))
    for i, (th, s) in enumerate(zip(TH, SIG)):
        a = math.radians(th) + s * math.radians(45)
        J[i] = (math.cos(a), math.sin(a), s * COS45 * Rw)
    return J


J = jacobian()


def speeds(twist):
    """omega_i (рад/с) по ИСПРАВЛЕННОЙ формуле sqrt(2)*u/r."""
    u = J @ np.array(twist, dtype=float)
    return u, math.sqrt(2.0) * u / R


def forces_eq(Fvec, Mz=0.0):
    """Равновесие min-norm: f_i = (ê_i·F)/2 + sigma_i*Mz/(4*sin45*RW)."""
    e = J[:, :2]                     # ê_i (столбцы 0,1)
    f = e @ np.array(Fvec, dtype=float) / 2.0
    f = f + np.array(SIG, dtype=float) * Mz / (4 * COS45 * RW)
    return f


def torques(f):
    """ИСПРАВЛЕННЫЙ момент: T = f*r*cos45."""
    return f * R * COS45


